    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String username = txtUsername.getText();
        String email = txtEmail.getText();
        String passwordHash = txtPasswordHash.getText();

        if (username.trim().isEmpty() || email.trim().isEmpty() || passwordHash.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Username, Email, and Password are required.");
            return;
        }

        // Inserts into the User table. The join_date is handled automatically by the DB
        String query = "INSERT INTO User (username, email, password_hash) VALUES (?, ?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setString(1, username);
            pst.setString(2, email);
            pst.setString(3, passwordHash);
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "User Saved Successfully!");
            
            txtUsername.setText("");
            txtEmail.setText("");
            txtPasswordHash.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            // MySQL error code 1062 indicates a duplicate entry for a unique key[cite: 17]
            if (ex.getErrorCode() == 1062) {
                javax.swing.JOptionPane.showMessageDialog(this, "This Username or Email already exists.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String userIdStr = txtUserId.getText();
        
        if (userIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a User ID to search.");
            return;
        }

        // Selects user details[cite: 17]
        String query = "SELECT username, email, password_hash, join_date FROM User WHERE user_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(userIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtUsername.setText(rs.getString("username"));
                txtEmail.setText(rs.getString("email"));
                txtPasswordHash.setText(rs.getString("password_hash"));
                
                // Retrieve and display the join date
                java.sql.Timestamp dbDate = rs.getTimestamp("join_date");
                txtJoinDate.setText(dbDate != null ? dbDate.toString() : "");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "User ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "User ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String userIdStr = txtUserId.getText();
        
        if (userIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the User ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this user?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM User WHERE user_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(userIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "User Deleted!");
                    txtUserId.setText("");
                    txtUsername.setText("");
                    txtEmail.setText("");
                    txtPasswordHash.setText("");
                    txtJoinDate.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "User ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete user. They have active data (playlists, subscriptions, history, etc.).");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

