    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String userIdStr = txtUserId.getText();
        String playlistName = txtPlaylistName.getText();

        if (userIdStr.trim().isEmpty() || playlistName.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "User ID and Playlist Name are required.");
            return;
        }

        String query = "INSERT INTO Playlist (user_id, name) VALUES (?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(userIdStr));
            pst.setString(2, playlistName);
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Playlist Created Successfully!");
            
            txtUserId.setText("");
            txtPlaylistName.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure the User ID exists.\n" + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "User ID must be a valid number.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String playlistIdStr = txtPlaylistId.getText();
        
        if (playlistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Playlist ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this playlist?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Playlist WHERE playlist_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(playlistIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Playlist Deleted!");
                    txtPlaylistId.setText("");
                    txtUserId.setText("");
                    txtPlaylistName.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Playlist ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete playlist. It currently contains songs.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String playlistIdStr = txtPlaylistId.getText();
        
        if (playlistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Playlist ID to search.");
            return;
        }

        String query = "SELECT user_id, name FROM Playlist WHERE playlist_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(playlistIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtUserId.setText(String.valueOf(rs.getInt("user_id")));
                txtPlaylistName.setText(rs.getString("name"));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Playlist ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Playlist ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

