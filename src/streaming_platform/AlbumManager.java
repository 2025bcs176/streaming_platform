    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String artistId = txtArtistId.getText();
        String title = txtTitle.getText();
        String coverUrl = txtCoverUrl.getText();
        
        // 1. Get the date directly from the JDateChooser
        java.util.Date utilDate = dateRelease.getDate();

        if (artistId.trim().isEmpty() || title.trim().isEmpty() || utilDate == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Artist ID, Title, and Release Date are required.");
            return;
        }

        // 2. Convert standard Java Date to SQL Date
        java.sql.Date sqlDate = new java.sql.Date(utilDate.getTime());

        String query = "INSERT INTO Album (artist_id, title, release_date, cover_image_url) VALUES (?, ?, ?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(artistId));
            pst.setString(2, title);
            pst.setDate(3, sqlDate); // 3. Pass the safe SQL date here
            pst.setString(4, coverUrl);
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Album Saved Successfully!");
            
            txtArtistId.setText("");
            txtTitle.setText("");
            dateRelease.setDate(null); // Clear the date chooser
            txtCoverUrl.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure the Artist ID exists.\n" + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Artist ID must be a number.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String albumIdStr = txtAlbumId.getText();
        
        if (albumIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter an Album ID to search.");
            return;
        }

        // Selects album details[cite: 17]
        String query = "SELECT artist_id, title, release_date, cover_image_url FROM Album WHERE album_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(albumIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtArtistId.setText(String.valueOf(rs.getInt("artist_id")));
                txtTitle.setText(rs.getString("title"));
                
                // Retrieve SQL date and set it in the JDateChooser
                java.sql.Date dbDate = rs.getDate("release_date");
                dateRelease.setDate(dbDate);
                
                txtCoverUrl.setText(rs.getString("cover_image_url"));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Album ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Album ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String albumIdStr = txtAlbumId.getText();
        
        if (albumIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Album ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this album?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Album WHERE album_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(albumIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Album Deleted!");
                    txtAlbumId.setText("");
                    txtArtistId.setText("");
                    txtTitle.setText("");
                    dateRelease.setDate(null);
                    txtCoverUrl.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Album ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete album. It may have linked Songs.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

