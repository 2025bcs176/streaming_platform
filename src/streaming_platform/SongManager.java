    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String albumIdStr = txtAlbumId.getText();
        String genreIdStr = txtGenreId.getText();
        String title = txtTitle.getText();
        String durationStr = txtDuration.getText();
        String filePath = txtFilePath.getText();

        if (albumIdStr.trim().isEmpty() || genreIdStr.trim().isEmpty() || title.trim().isEmpty() || durationStr.trim().isEmpty() || filePath.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "All fields (except Song ID) are required to save a song.");
            return;
        }

        // Inserts into the Song table
        String query = "INSERT INTO Song (album_id, genre_id, title, duration_seconds, file_path) VALUES (?, ?, ?, ?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(albumIdStr));
            pst.setInt(2, Integer.parseInt(genreIdStr));
            pst.setString(3, title);
            pst.setInt(4, Integer.parseInt(durationStr));
            pst.setString(5, filePath);
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Song Saved Successfully!");
            
            // Clear fields
            txtAlbumId.setText("");
            txtGenreId.setText("");
            txtTitle.setText("");
            txtDuration.setText("");
            txtFilePath.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure the Album ID and Genre ID exist.\n" + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "IDs and Duration must be valid numbers.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String songIdStr = txtSongId.getText();
        
        if (songIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Song ID to search.");
            return;
        }

        // Retrieves song details[cite: 17]
        String query = "SELECT album_id, genre_id, title, duration_seconds, file_path FROM Song WHERE song_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(songIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtAlbumId.setText(String.valueOf(rs.getInt("album_id")));
                txtGenreId.setText(String.valueOf(rs.getInt("genre_id")));
                txtTitle.setText(rs.getString("title"));
                txtDuration.setText(String.valueOf(rs.getInt("duration_seconds")));
                txtFilePath.setText(rs.getString("file_path"));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Song ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Song ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String songIdStr = txtSongId.getText();
        
        if (songIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Song ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this song?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Song WHERE song_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(songIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Song Deleted!");
                    txtSongId.setText("");
                    txtAlbumId.setText("");
                    txtGenreId.setText("");
                    txtTitle.setText("");
                    txtDuration.setText("");
                    txtFilePath.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Song ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete song. It may be linked to a Playlist or Listening History.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

