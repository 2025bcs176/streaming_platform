    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String userIdStr = txtUserId.getText();
        String planIdStr = txtPlanId.getText();
        String amountPaidStr = txtAmountPaid.getText();
        String paymentMethod = txtPaymentMethod.getText();

        if (userIdStr.trim().isEmpty() || planIdStr.trim().isEmpty() || amountPaidStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "User ID, Plan ID, and Amount Paid are required.");
            return;
        }

        // Inserts into the Payment table[cite: 17]
        String query = "INSERT INTO Payment (user_id, plan_id, amount_paid, payment_method) VALUES (?, ?, ?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(userIdStr));
            pst.setInt(2, Integer.parseInt(planIdStr));
            pst.setBigDecimal(3, new java.math.BigDecimal(amountPaidStr));
            pst.setString(4, paymentMethod);
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Payment Logged Successfully!");
            
            txtUserId.setText("");
            txtPlanId.setText("");
            txtAmountPaid.setText("");
            txtPaymentMethod.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure the User ID and Plan ID exist.\n" + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "IDs must be integers and Amount must be a decimal.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String receiptIdStr = txtReceiptId.getText();
        
        if (receiptIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Receipt ID to search.");
            return;
        }

        String query = "SELECT user_id, plan_id, amount_paid, payment_method FROM Payment WHERE receipt_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(receiptIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtUserId.setText(String.valueOf(rs.getInt("user_id")));
                txtPlanId.setText(String.valueOf(rs.getInt("plan_id")));
                txtAmountPaid.setText(rs.getBigDecimal("amount_paid").toString());
                txtPaymentMethod.setText(rs.getString("payment_method"));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Receipt ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Receipt ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String receiptIdStr = txtReceiptId.getText();
        
        if (receiptIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Receipt ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this payment record?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Payment WHERE receipt_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(receiptIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Payment Record Deleted!");
                    txtReceiptId.setText("");
                    txtUserId.setText("");
                    txtPlanId.setText("");
                    txtAmountPaid.setText("");
                    txtPaymentMethod.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Receipt ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

