    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String hostArtistIdStr = txtHostArtistId.getText();
        String title = txtTitle.getText();
        String description = txtDescription.getText();
        String category = txtCategory.getText();

        if (hostArtistIdStr.trim().isEmpty() || title.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Host Artist ID and Title are required.");
            return;
        }

        // Inserts into the Podcast table[cite: 17]
        String query = "INSERT INTO Podcast (host_artist_id, title, description, category) VALUES (?, ?, ?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(hostArtistIdStr));
            pst.setString(2, title);
            pst.setString(3, description);
            pst.setString(4, category);
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Podcast Saved Successfully!");
            
            txtHostArtistId.setText("");
            txtTitle.setText("");
            txtDescription.setText("");
            txtCategory.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure the Host Artist ID exists in the Artist table.\n" + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Host Artist ID must be a valid number.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String podcastIdStr = txtPodcastId.getText();
        
        if (podcastIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Podcast ID to search.");
            return;
        }

        // Retrieves podcast details[cite: 17]
        String query = "SELECT host_artist_id, title, description, category FROM Podcast WHERE podcast_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(podcastIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtHostArtistId.setText(String.valueOf(rs.getInt("host_artist_id")));
                txtTitle.setText(rs.getString("title"));
                txtDescription.setText(rs.getString("description"));
                txtCategory.setText(rs.getString("category"));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Podcast ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Podcast ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String podcastIdStr = txtPodcastId.getText();
        
        if (podcastIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Podcast ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this podcast?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Podcast WHERE podcast_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(podcastIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Podcast Deleted!");
                    txtPodcastId.setText("");
                    txtHostArtistId.setText("");
                    txtTitle.setText("");
                    txtDescription.setText("");
                    txtCategory.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Podcast ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete podcast. It may have linked Podcast Episodes.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

