    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String stageName = txtStageName.getText();
    String bio = txtBio.getText();
    boolean isVerified = chkVerified.isSelected();

    if (stageName.trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Stage Name is required.");
        return;
    }

    String query = "INSERT INTO Artist (stage_name, bio, verified) VALUES (?, ?, ?)";

    try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
         java.sql.PreparedStatement pst = con.prepareStatement(query)) {
        
        pst.setString(1, stageName);
        pst.setString(2, bio);
        pst.setBoolean(3, isVerified);
        
        pst.executeUpdate();
        javax.swing.JOptionPane.showMessageDialog(this, "Artist Saved Successfully!");
        
        // Clear fields
        txtStageName.setText("");
        txtBio.setText("");
        chkVerified.setSelected(false);
        
    } catch (java.sql.SQLException ex) {
        ex.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String idStr = txtArtistId.getText();
    
    if (idStr.trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter an Artist ID to search.");
        return;
    }

    String query = "SELECT stage_name, bio, verified FROM Artist WHERE artist_id = ?";

    try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
         java.sql.PreparedStatement pst = con.prepareStatement(query)) {
        
        pst.setInt(1, Integer.parseInt(idStr));
        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            txtStageName.setText(rs.getString("stage_name"));
            txtBio.setText(rs.getString("bio"));
            chkVerified.setSelected(rs.getBoolean("verified"));
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Artist ID not found.");
        }
        
    } catch (java.sql.SQLException ex) {
        ex.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Artist ID must be a number.");
    }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String idStr = txtArtistId.getText();
    
    if (idStr.trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Artist ID to delete.");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this artist?", "Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);
    
    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
        String query = "DELETE FROM Artist WHERE artist_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(idStr));
            int rowsAffected = pst.executeUpdate();

            if (rowsAffected > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Artist Deleted!");
                txtArtistId.setText("");
                txtStageName.setText("");
                txtBio.setText("");
                chkVerified.setSelected(false);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Artist ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete artist. They may be linked to an Album or Podcast.");
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

