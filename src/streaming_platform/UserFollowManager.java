    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String userIdStr = txtUserId.getText();
        String artistIdStr = txtArtistId.getText();

        if (userIdStr.trim().isEmpty() || artistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Both User ID and Artist ID are required.");
            return;
        }

        String query = "INSERT INTO User_Follow (user_id, artist_id) VALUES (?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(userIdStr));
            pst.setInt(2, Integer.parseInt(artistIdStr));
            pst.executeUpdate();
            
            javax.swing.JOptionPane.showMessageDialog(this, "User is now following the Artist!");
            txtArtistId.setText(""); 
            
        } catch (java.sql.SQLException ex) {
            if (ex.getErrorCode() == 1062) {
                javax.swing.JOptionPane.showMessageDialog(this, "This user already follows this artist.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure both IDs exist.");
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "IDs must be valid numbers.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String userIdStr = txtUserId.getText();
        String artistIdStr = txtArtistId.getText();
        
        if (userIdStr.trim().isEmpty() || artistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both IDs to unfollow.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Unfollow this artist?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM User_Follow WHERE user_id = ? AND artist_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(userIdStr));
                pst.setInt(2, Integer.parseInt(artistIdStr));
                
                if (pst.executeUpdate() > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "User successfully unfollowed the artist!");
                    txtArtistId.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Record not found.");
                }
            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String userIdStr = txtUserId.getText();
        String artistIdStr = txtArtistId.getText();
        
        if (userIdStr.trim().isEmpty() || artistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both User ID and Artist ID to search.");
            return;
        }

        String query = "SELECT user_id FROM User_Follow WHERE user_id = ? AND artist_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(userIdStr));
            pst.setInt(2, Integer.parseInt(artistIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Confirmed: User follows this artist.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "User does NOT follow this artist.");
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

