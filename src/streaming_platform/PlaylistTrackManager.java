    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String playlistIdStr = txtPlaylistId.getText();
        String songIdStr = txtSongId.getText();

        if (playlistIdStr.trim().isEmpty() || songIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Both Playlist ID and Song ID are required.");
            return;
        }

        String query = "INSERT INTO Playlist_Track (playlist_id, song_id) VALUES (?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(playlistIdStr));
            pst.setInt(2, Integer.parseInt(songIdStr));
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Song Added to Playlist Successfully!");
            
            // We clear only the song ID to make it easy to add multiple songs to the same playlist
            txtSongId.setText("");
            txtSongId.requestFocus();
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            if (ex.getErrorCode() == 1062) {
                javax.swing.JOptionPane.showMessageDialog(this, "This song is already in this playlist.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure both IDs exist.\n" + ex.getMessage());
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "IDs must be valid numbers.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String playlistIdStr = txtPlaylistId.getText();
        String songIdStr = txtSongId.getText();
        
        if (playlistIdStr.trim().isEmpty() || songIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both Playlist ID and Song ID to search.");
            return;
        }

        String query = "SELECT playlist_id FROM Playlist_Track WHERE playlist_id = ? AND song_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(playlistIdStr));
            pst.setInt(2, Integer.parseInt(songIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Confirmed: This song is currently in the playlist.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "This song is NOT in the specified playlist.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "IDs must be valid numbers.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String playlistIdStr = txtPlaylistId.getText();
        String songIdStr = txtSongId.getText();
        
        if (playlistIdStr.trim().isEmpty() || songIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both Playlist ID and Song ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Remove this song from the playlist?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Playlist_Track WHERE playlist_id = ? AND song_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(playlistIdStr));
                pst.setInt(2, Integer.parseInt(songIdStr));
                
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Song Removed from Playlist!");
                    txtSongId.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Record not found. The song is not in this playlist.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

