    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String podcastIdStr = txtPodcastId.getText();
        String title = txtTitle.getText();
        String description = txtDescription.getText();
        String durationStr = txtDuration.getText();

        if (podcastIdStr.trim().isEmpty() || title.trim().isEmpty() || durationStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Podcast ID, Title, and Duration are required.");
            return;
        }

        // Inserts into the Podcast_Episode table
        String query = "INSERT INTO Podcast_Episode (podcast_id, title, description, duration_seconds) VALUES (?, ?, ?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(podcastIdStr));
            pst.setString(2, title);
            pst.setString(3, description);
            pst.setInt(4, Integer.parseInt(durationStr));
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Episode Saved Successfully!");
            
            txtPodcastId.setText("");
            txtTitle.setText("");
            txtDescription.setText("");
            txtDuration.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure the Podcast ID exists.\n" + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Podcast ID and Duration must be valid numbers.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String episodeIdStr = txtEpisodeId.getText();
        
        if (episodeIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter an Episode ID to search.");
            return;
        }

        String query = "SELECT podcast_id, title, description, duration_seconds FROM Podcast_Episode WHERE episode_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(episodeIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtPodcastId.setText(String.valueOf(rs.getInt("podcast_id")));
                txtTitle.setText(rs.getString("title"));
                txtDescription.setText(rs.getString("description"));
                txtDuration.setText(String.valueOf(rs.getInt("duration_seconds")));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Episode ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Episode ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String episodeIdStr = txtEpisodeId.getText();
        
        if (episodeIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Episode ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this episode?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Podcast_Episode WHERE episode_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(episodeIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Episode Deleted!");
                    txtEpisodeId.setText("");
                    txtPodcastId.setText("");
                    txtTitle.setText("");
                    txtDescription.setText("");
                    txtDuration.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Episode ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

