    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String genreName = txtGenreName.getText();

        if (genreName.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Genre Name is required.");
            return;
        }

        // Inserts into the Genre table
        String query = "INSERT INTO Genre (genre_name) VALUES (?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setString(1, genreName);
            pst.executeUpdate();
            
            javax.swing.JOptionPane.showMessageDialog(this, "Genre Saved Successfully!");
            txtGenreName.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            // Catches the error if a duplicate genre name is entered[cite: 17]
            if (ex.getErrorCode() == 1062) {
                javax.swing.JOptionPane.showMessageDialog(this, "This Genre already exists.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String genreIdStr = txtGenreId.getText();
        
        if (genreIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Genre ID to search.");
            return;
        }

        // Selects the genre name[cite: 17]
        String query = "SELECT genre_name FROM Genre WHERE genre_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(genreIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtGenreName.setText(rs.getString("genre_name"));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Genre ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Genre ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String genreIdStr = txtGenreId.getText();
        
        if (genreIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Genre ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this genre?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Genre WHERE genre_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(genreIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Genre Deleted!");
                    txtGenreId.setText("");
                    txtGenreName.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Genre ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete genre. It is currently linked to existing Songs.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

