    private void generateReport(String query) {
        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query);
             java.sql.ResultSet rs = pst.executeQuery()) {

            java.sql.ResultSetMetaData metaData = rs.getMetaData();
            int columnCount = metaData.getColumnCount();

            // Get Column Names from the Database
            java.util.Vector<String> columnNames = new java.util.Vector<>();
            for (int column = 1; column <= columnCount; column++) {
                // Use getColumnLabel to respect the SQL "AS" aliases
                columnNames.add(metaData.getColumnLabel(column)); 
            }

            // Get Row Data
            java.util.Vector<java.util.Vector<Object>> data = new java.util.Vector<>();
            while (rs.next()) {
                java.util.Vector<Object> vector = new java.util.Vector<>();
                for (int columnIndex = 1; columnIndex <= columnCount; columnIndex++) {
                    vector.add(rs.getObject(columnIndex));
                }
                data.add(vector);
            }

            // Apply the data to the JTable
            javax.swing.table.DefaultTableModel tableModel = new javax.swing.table.DefaultTableModel(data, columnNames);
            tblReport.setModel(tableModel);

        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        }
    }
    
