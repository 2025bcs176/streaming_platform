    private void btnExportPdfActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportPdfActionPerformed
        
        if (tblReport.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "No data to export! Please generate a report first.");
            return;
        }

        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Save PDF Report");
        int userSelection = fileChooser.showSaveDialog(this);

        if (userSelection == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File fileToSave = fileChooser.getSelectedFile();
            String filePath = fileToSave.getAbsolutePath();
            
            if (!filePath.toLowerCase().endsWith(".pdf")) {
                filePath += ".pdf";
            }

            try {
                Document document = new Document();
                PdfWriter.getInstance(document, new FileOutputStream(filePath));
                document.open();

                // 1. Stylized Company Headers (Right Aligned)[cite: 3]
                Font blueFont = FontFactory.getFont(FontFactory.HELVETICA, 18, Font.NORMAL, BaseColor.BLUE);
                Paragraph para1 = new Paragraph("Streaming Platform Inc.", blueFont);
                para1.setAlignment(Paragraph.ALIGN_RIGHT);
                document.add(para1);
                
                Paragraph para2 = new Paragraph("P.O.BOX 1245", blueFont);
                para2.setAlignment(Paragraph.ALIGN_RIGHT);
                document.add(para2);
                
                // 2. Add Current Date (Left Aligned)[cite: 3]
                Paragraph datePara = new Paragraph(new java.util.Date().toString(), FontFactory.getFont(FontFactory.TIMES_ROMAN, 11, Font.BOLD, BaseColor.BLUE));
                datePara.setAlignment(Paragraph.ALIGN_LEFT);
                document.add(datePara);
                document.add(new Paragraph(" "));

                // 3. Format the PDF Table[cite: 3]
                PdfPTable pdfTable = new PdfPTable(tblReport.getColumnCount());
                pdfTable.setWidthPercentage(100);
                pdfTable.setSpacingBefore(10f);
                pdfTable.setSpacingAfter(10f);

                // 4. Create a spanning title cell with background color[cite: 3]
                PdfPCell titleCell = new PdfPCell(new Paragraph("Comprehensive Data Report", blueFont));
                titleCell.setColspan(tblReport.getColumnCount());
                titleCell.setHorizontalAlignment(Element.ALIGN_CENTER);
                titleCell.setBackgroundColor(BaseColor.DARK_GRAY);
                pdfTable.addCell(titleCell);

                // Add standard column headers
                for (int i = 0; i < tblReport.getColumnCount(); i++) {
                    pdfTable.addCell(new Phrase(tblReport.getColumnName(i)));
                }

                // Add row data
                for (int rows = 0; rows < tblReport.getRowCount(); rows++) {
                    for (int cols = 0; cols < tblReport.getColumnCount(); cols++) {
                        Object val = tblReport.getValueAt(rows, cols);
                        pdfTable.addCell(new Phrase(val != null ? val.toString() : ""));
                    }
                }

                document.add(pdfTable);
                document.close();
                
                javax.swing.JOptionPane.showMessageDialog(this, "PDF Report exported successfully!");

                // 5. Automatically open the saved PDF file[cite: 2]
                File myfile = new File(filePath);
                try {
                    if (Desktop.isDesktopSupported() && Desktop.getDesktop().isSupported(Desktop.Action.OPEN)) {
                        Desktop.getDesktop().open(myfile);
                    } else {
                        System.out.println("Desktop API not supported. Using Ubuntu xdg-open fallback...");
                        Runtime.getRuntime().exec(new String[]{"xdg-open", myfile.getAbsolutePath()});
                    }
                } catch (java.io.IOException ex) {
                    System.err.println("Could not open the PDF automatically.");
                    ex.printStackTrace();
                }

            } catch (Exception ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Error generating PDF: " + ex.getMessage());
            }
        }
    
    
    }//GEN-LAST:event_btnExportPdfActionPerformed

