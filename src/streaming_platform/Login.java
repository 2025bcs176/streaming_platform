    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());

        if (username.trim().isEmpty() || password.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both Username and Password.");
            return;
        }
        
        // Database connection parameters
        String url = "jdbc:mysql://localhost:3306/streaming_platform";
        String dbUser = "root"; // Update with your MySQL username
        String dbPassword = "YourNewPassword123!"; // Update with your MySQL password

        // Querying the User table[cite: 17]
        // Notice we added is_admin to the SELECT statement
        String query = "SELECT user_id, is_admin FROM User WHERE username = ? AND password_hash = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setString(1, username);
            pst.setString(2, password); 
            
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                // Capture whether the user is an admin
                boolean isAdmin = rs.getBoolean("is_admin");
                
                javax.swing.JOptionPane.showMessageDialog(this, "Login Successful!");
                
                // Pass the admin status to the Menu
                new Menu(isAdmin).setVisible(true);
                
                this.dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Invalid Username or Password", "Login Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
                txtPassword.setText("");
                txtPassword.requestFocus();
            }

        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Connection Error: " + ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

