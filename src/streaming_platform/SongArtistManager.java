    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String songIdStr = txtSongId.getText();
        String artistIdStr = txtArtistId.getText();
        
        if (songIdStr.trim().isEmpty() || artistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both Song ID and Artist ID to search.");
            return;
        }

        String query = "SELECT song_id FROM Song_Artist WHERE song_id = ? AND artist_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(songIdStr));
            pst.setInt(2, Integer.parseInt(artistIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Confirmed: This artist is linked to this song.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "This artist is NOT linked to this song.");
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String songIdStr = txtSongId.getText();
        String artistIdStr = txtArtistId.getText();
        
        if (songIdStr.trim().isEmpty() || artistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both IDs to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Remove this artist from this song?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Song_Artist WHERE song_id = ? AND artist_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(songIdStr));
                pst.setInt(2, Integer.parseInt(artistIdStr));
                
                if (pst.executeUpdate() > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Artist Unlinked!");
                    txtArtistId.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Record not found.");
                }
            } catch (Exception ex) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String songIdStr = txtSongId.getText();
        String artistIdStr = txtArtistId.getText();

        if (songIdStr.trim().isEmpty() || artistIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Both Song ID and Artist ID are required.");
            return;
        }

        String query = "INSERT INTO Song_Artist (song_id, artist_id) VALUES (?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(songIdStr));
            pst.setInt(2, Integer.parseInt(artistIdStr));
            pst.executeUpdate();
            
            javax.swing.JOptionPane.showMessageDialog(this, "Artist Linked to Song Successfully!");
            txtArtistId.setText(""); // Clear artist to easily add another to the same song
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            if (ex.getErrorCode() == 1062) {
                javax.swing.JOptionPane.showMessageDialog(this, "This artist is already linked to this song.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Database Error: Ensure both IDs exist.");
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "IDs must be valid numbers.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

