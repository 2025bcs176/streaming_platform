    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String planName = txtPlanName.getText();
        String priceStr = txtPrice.getText();
        String maxDevicesStr = txtMaxDevices.getText();
        String resolution = txtResolution.getText();

        if (planName.trim().isEmpty() || priceStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Plan Name and Price are required.");
            return;
        }

        // Inserts into the Subscription_Plan table[cite: 17]
        String query = "INSERT INTO Subscription_Plan (plan_name, price, max_devices, resolution_quality) VALUES (?, ?, ?, ?)";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setString(1, planName);
            pst.setBigDecimal(2, new java.math.BigDecimal(priceStr));
            
            // Handle optional max devices default
            if (maxDevicesStr.trim().isEmpty()) {
                pst.setInt(3, 1); // Default to 1 device[cite: 17]
            } else {
                pst.setInt(3, Integer.parseInt(maxDevicesStr));
            }
            
            pst.setString(4, resolution);
            
            pst.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Subscription Plan Saved Successfully!");
            
            txtPlanName.setText("");
            txtPrice.setText("");
            txtMaxDevices.setText("");
            txtResolution.setText("");
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Price and Max Devices must be valid numbers.");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String planIdStr = txtPlanId.getText();
        
        if (planIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a Plan ID to search.");
            return;
        }

        // Selects plan details[cite: 17]
        String query = "SELECT plan_name, price, max_devices, resolution_quality FROM Subscription_Plan WHERE plan_id = ?";

        try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
             java.sql.PreparedStatement pst = con.prepareStatement(query)) {
            
            pst.setInt(1, Integer.parseInt(planIdStr));
            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                txtPlanName.setText(rs.getString("plan_name"));
                txtPrice.setText(rs.getBigDecimal("price").toString());
                txtMaxDevices.setText(String.valueOf(rs.getInt("max_devices")));
                txtResolution.setText(rs.getString("resolution_quality"));
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Plan ID not found.");
            }
            
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage());
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Plan ID must be a number.");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String planIdStr = txtPlanId.getText();
        
        if (planIdStr.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Plan ID to delete.");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this plan?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String query = "DELETE FROM Subscription_Plan WHERE plan_id = ?";

            try (java.sql.Connection con = java.sql.DriverManager.getConnection(url, dbUser, dbPassword);
                 java.sql.PreparedStatement pst = con.prepareStatement(query)) {
                
                pst.setInt(1, Integer.parseInt(planIdStr));
                int rowsAffected = pst.executeUpdate();

                if (rowsAffected > 0) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Plan Deleted!");
                    txtPlanId.setText("");
                    txtPlanName.setText("");
                    txtPrice.setText("");
                    txtMaxDevices.setText("");
                    txtResolution.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Plan ID not found.");
                }
                
            } catch (java.sql.SQLException ex) {
                ex.printStackTrace();
                javax.swing.JOptionPane.showMessageDialog(this, "Cannot delete plan. It is linked to existing user subscriptions or payments.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

